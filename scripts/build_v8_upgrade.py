def snapshot_pre_v8() -> dict:
    snap_root = STAGING / "pre_v8_canonical_snapshots"
    manifest: list[dict] = []
    patterns = [
        "pilot_report*/pilot_result.json",
        "pilot_report*/pilot_result.md",
        "raw_predictions*/provenance.json",
        "tables/main200_*.csv",
        "tables/main200_*.tex",
    ]
    for pattern in patterns:
        for src in sorted(RESULTS.glob(pattern)):
            rel = src.relative_to(RESULTS)
            dest = snap_root / rel
            dest.parent.mkdir(parents=True, exist_ok=True)
            if not dest.exists():
                shutil.copy2(src, dest)
            manifest.append({
                "source": _rel(src),
                "snapshot": _rel(dest),
                "sha256": _sha256_file(src),
            })
    out = {
        "schema": "certvic.v8.pre_snapshot.v1",
        "created_utc": datetime.now(timezone.utc).isoformat(),
        "n_files": len(manifest),
        "files": manifest,
    }
    write_json(STAGING / "pre_v8_snapshot_manifest.json", out)
    return out


def inventory_newruns() -> dict:
    files: list[dict] = []
    if not NEWRUNS.exists():
        result = {
            "schema": "certvic.v8.newruns_inventory.v1",
            "status": "blocked",
            "root": _rel(NEWRUNS),
            "missing_root": True,
            "files": [],
        }
        write_json(V8 / "newruns_file_inventory.json", result)
        _write_text(V8 / "NEWRUNS_FILE_INVENTORY.md", "# V8 Newruns File Inventory\n\nBLOCKED: `kaggleoutputs/newruns` is missing.\n")
        return result
    for path in sorted(NEWRUNS.rglob("*")):
        if not path.is_file():
            continue
        entry = {
            "path": _rel(path),
            "size_bytes": path.stat().st_size,
            "sha256": _sha256_file(path),
            "kind": "zip" if path.suffix == ".zip" else path.suffix.lstrip("."),
        }
        if path.suffix == ".zip":
            members = []
            with zipfile.ZipFile(path) as zf:
                for info in sorted(zf.infolist(), key=lambda x: x.filename):
                    if info.is_dir():
                        continue
                    data = zf.read(info.filename)
                    members.append({
                        "name": info.filename,
                        "size_bytes": info.file_size,
                        "sha256": _sha256_bytes(data),
                    })
            entry["members"] = members
        files.append(entry)
    result = {
        "schema": "certvic.v8.newruns_inventory.v1",
        "status": "complete",
        "root": _rel(NEWRUNS),
        "missing_root": False,
        "n_files": len(files),
        "files": files,
    }
    write_json(V8 / "newruns_file_inventory.json", result)
    lines = [
        "# V8 Newruns File Inventory",
        "",
        f"Root: `{_rel(NEWRUNS)}`",
        "",
        "| file | bytes | sha256 | notes |",
        "| --- | ---: | --- | --- |",
    ]
    for f in files:
        note = f"{len(f.get('members', []))} zip members" if f["kind"] == "zip" else ""
        lines.append(f"| `{f['path']}` | {f['size_bytes']} | `{f['sha256']}` | {note} |")
    lines.append("")
    _write_text(V8 / "NEWRUNS_FILE_INVENTORY.md", "\n".join(lines))
    return result


def _validate_rows(rows: list[dict], provider: str, run_tag: str, expected_rows: int) -> dict:
    provider_names = sorted({r.get("provider_name") for r in rows})
    if run_tag in {"spurious", "perception_scaled"}:
        ids = [f"{r.get('item_id')}::{r.get('image_variant')}" for r in rows]
    else:
        ids = [str(r.get("prediction_id") or f"{r.get('item_id')}::{r.get('image_variant')}::{i}") for i, r in enumerate(rows)]
    dupes = sorted(k for k, n in Counter(ids).items() if n > 1)
    parse_values = [r.get("parse_ok") for r in rows]
    return {
        "n_rows": len(rows),
        "expected_rows": expected_rows,
        "row_count_ok": len(rows) == expected_rows,
        "provider_names": provider_names,
        "provider_ok": provider_names == [provider],
        "n_duplicate_ids": len(dupes),
        "duplicate_ids_preview": dupes[:10],
        "parse_ok": sum(1 for v in parse_values if v is True),
        "parse_rate": round(sum(1 for v in parse_values if v is True) / len(rows), 4) if rows else None,
    }


def _candidate_direct(provider: str, run_tag: str) -> Path:
    return NEWRUNS / RUNS[run_tag]["filename"].format(provider=provider)


def _candidate_zip_member(provider: str, run_tag: str) -> tuple[Path, str] | None:
    zpath = NEWRUNS / RUNS[run_tag]["zip"].format(provider=provider)
    member = RUNS[run_tag]["filename"].format(provider=provider)
    if not zpath.exists():
        return None
    with zipfile.ZipFile(zpath) as zf:
        if member in zf.namelist():
            return zpath, member
    return None


def _extract_zip_member(zpath: Path, member: str) -> Path:
    if member.startswith("/") or ".." in Path(member).parts:
        raise SystemExit(f"REFUSED: unsafe zip member path: {member}")
    out = STAGING / "newruns_extracted" / zpath.stem / member
    out.parent.mkdir(parents=True, exist_ok=True)
    with zipfile.ZipFile(zpath) as zf:
        data = zf.read(member)
    out.write_bytes(data)
    return out


def normalize_predictions() -> dict:
    manifest: dict[str, dict] = {}
    failures: list[str] = []
    for run_tag, cfg in RUNS.items():
        for provider in PROVIDERS:
            expected_rows = cfg["expected_rows"]
            attempts: list[dict] = []
            chosen: Path | None = None
            chosen_source = ""

            direct = _candidate_direct(provider, run_tag)
            if direct.exists():
                rows = _read_jsonl(direct)
                audit = _validate_rows(rows, provider, run_tag, expected_rows)
                attempts.append({"source": _rel(direct), "source_kind": "direct", **audit})
                if audit["row_count_ok"] and audit["provider_ok"] and audit["n_duplicate_ids"] == 0:
                    chosen = direct
                    chosen_source = "direct"

            if chosen is None:
                zip_candidate = _candidate_zip_member(provider, run_tag)
                if zip_candidate is not None:
                    zpath, member = zip_candidate
                    extracted = _extract_zip_member(zpath, member)
                    rows = _read_jsonl(extracted)
                    audit = _validate_rows(rows, provider, run_tag, expected_rows)
                    attempts.append({
                        "source": f"{_rel(zpath)}::{member}",
                        "extracted_path": _rel(extracted),
                        "source_kind": "zip_member",
                        **audit,
                    })
                    if audit["row_count_ok"] and audit["provider_ok"] and audit["n_duplicate_ids"] == 0:
                        chosen = extracted
                        chosen_source = "zip_member"

            dest = cfg["dest_dir"] / cfg["filename"].format(provider=provider)
            key = f"{provider}__{run_tag}"
            if chosen is None:
                failures.append(f"{key}: no valid complete prediction file")
                manifest[key] = {
                    "provider": provider,
                    "run_tag": run_tag,
                    "status": "blocked",
                    "destination": _rel(dest),
                    "attempts": attempts,
                }
                continue
            copy_status, err = _copy_if_missing_or_identical(chosen, dest)
            if err:
                failures.append(f"{key}: {err}")
            rows = _read_jsonl(chosen)
            manifest[key] = {
                "provider": provider,
                "run_tag": run_tag,
                "status": "complete" if not err else "blocked",
                "source": _rel(chosen),
                "source_kind": chosen_source,
                "destination": _rel(dest),
                "copy_status": copy_status,
                "sha256": _sha256_file(chosen),
                "attempts": attempts,
                "validation": _validate_rows(rows, provider, run_tag, expected_rows),
            }

    result = {
        "schema": "certvic.v8.canonical_prediction_manifest.v1",
        "status": "blocked" if failures else "complete",
        "produced_model_results_by_this_script": False,
        "ingested_existing_kaggle_predictions": True,
        "paper_evidence": False,
        "failures": failures,
        "entries": manifest,
    }
    write_json(V8 / "canonical_prediction_manifest.json", result)
    write_json(V8 / "prediction_integrity_audit.json", result)
    _write_text(V8 / "canonical_prediction_manifest.md", _canonical_manifest_md(result))
    _write_text(V8 / "prediction_integrity_audit.md", _canonical_manifest_md(result))
    return result


def _canonical_manifest_md(result: dict) -> str:
    lines = [
        "# V8 Canonical Prediction Manifest",
        "",
        f"`status={result['status']}` `paper_evidence=false` `produced_model_results_by_this_script=false`",
        "",
        "| provider | run | rows | source | destination | status |",
        "| --- | --- | ---: | --- | --- | --- |",
    ]
    for key in sorted(result["entries"]):
        e = result["entries"][key]
        val = e.get("validation") or {}
        lines.append(
            f"| `{e['provider']}` | `{e['run_tag']}` | {val.get('n_rows', '')} | "
            f"`{e.get('source', '')}` | `{e['destination']}` | {e['status']} |"
        )
    if result["failures"]:
        lines += ["", "## Failures", ""]
        lines.extend(f"- {f}" for f in result["failures"])
    lines.append("")
    return "\n".join(lines)


def run_commands() -> list[dict]:
    commands: list[list[str]] = []
    for provider in PROVIDERS:
        commands.append([
            "python3", "scripts/pilot_report_from_raw.py",
            "--provider", provider,
            "--model-name", MODEL_NAMES[provider],
            "--run-label", provider,
            "--raw-spurious", str(RUNS["spurious"]["dest_dir"] / RUNS["spurious"]["filename"].format(provider=provider)),
            "--raw-perception-scaled", str(RUNS["perception_scaled"]["dest_dir"] / RUNS["perception_scaled"]["filename"].format(provider=provider)),
        ])
    commands += [
        [
            "python3", "-m", "certvic.validation.edit_detectability",
            "--tasks", "data/edits/spurious_flip_control/pilot_eval_tasks_reviewed.jsonl",
            "--out-dir", "data/results/spurious_flip_control/edit_detectability",
        ],
        ["python3", "-m", "certvic.v7.spurious_control_integration"],
        ["python3", "scripts/build_multimodel_summary.py"],
        ["python3", "scripts/build_main200_paper_tables.py"],
    ]
    logs: list[dict] = []
    for cmd in commands:
        proc = subprocess.run(cmd, cwd=REPO, text=True, capture_output=True, check=False)
        log = {
            "cmd": cmd,
            "returncode": proc.returncode,
            "stdout_tail": proc.stdout[-4000:],
            "stderr_tail": proc.stderr[-4000:],
        }
        logs.append(log)
        if proc.returncode != 0:
            write_json(REPORTS / "command_log.json", {"commands": logs})
            raise SystemExit(f"Command failed: {' '.join(cmd)}\n{proc.stderr[-1200:]}")
    write_json(REPORTS / "command_log.json", {"commands": logs})
    return logs


def _load_pilot_results() -> dict[str, dict]:
    out = {}
    for path in sorted(RESULTS.glob("pilot_report*/pilot_result.json")):
        data = _read_json(path)
        prov = data.get("provider")
        if prov:
            out[prov] = data
    return out


def build_spurious_report() -> dict:
    integration_path = RESULTS / "control_irrelevant_report/control_irrelevant_report.json"
    integration = _read_json(integration_path) if integration_path.exists() else {}
    pilot = _load_pilot_results()
    providers: dict[str, dict] = {}
    for provider in PROVIDERS:
        sp = (pilot.get(provider) or {}).get("spurious_flip_control") or (integration.get("metrics") or {}).get(provider) or {}
        providers[provider] = {
            "n_items": sp.get("n_items") or sp.get("n_scored"),
            "flipped": sp.get("flipped"),
            "spurious_flip_rate": sp.get("spurious_flip_rate"),
            "gate_threshold": sp.get("gate_threshold", SPURIOUS_THRESHOLD),
            "gate_pass": bool(sp.get("gate_pass")),
            "raw_prediction": _rel(RUNS["spurious"]["dest_dir"] / RUNS["spurious"]["filename"].format(provider=provider)),
        }
    all_pass = all(p["gate_pass"] for p in providers.values())
    status = "complete_pass" if all_pass else "blocked_failed_gate"
    detectability = _collect_detectability_status()
    result = {
        "schema": "certvic.v8.spurious_specificity_control_report.v1",
        "status": status,
        "evidence_status": "SPECIFICITY_CONTROL_PILOT_NON_EVIDENCE",
        "paper_evidence": False,
        "all_provider_gate_pass": all_pass,
        "providers": providers,
        "detectability_quality": detectability,
        "integration_status": {
            "path": _rel(integration_path),
            "status": integration.get("status"),
            "specificity_status": integration.get("specificity_status"),
            "gate_errors": integration.get("gate_errors", []),
        },
        "interpretation": "Specificity is not cleared unless every provider passes the configured spurious-flip gate.",
    }
    write_json(V8 / "spurious_specificity_control_report.json", result)
    write_json(V8 / "SPURIOUS_SPECIFICITY_CONTROL_REPORT.json", result)
    _write_text(V8 / "SPURIOUS_SPECIFICITY_CONTROL_REPORT.md", _spurious_md(result))
    return result


def _collect_detectability_status() -> dict:
    root = REPO / "data/results/spurious_flip_control/edit_detectability"
    files = sorted(root.rglob("*.json")) if root.exists() else []
    payloads = []
    for path in files:
        try:
            data = _read_json(path)
        except json.JSONDecodeError:
            continue
        payloads.append({"path": _rel(path), "keys": sorted(data.keys()), "data": data})
    return {
        "out_dir": _rel(root),
        "exists": root.exists(),
        "json_reports": payloads,
    }


