def build_task_ledger(spurious: dict, scaled: dict, polarity: dict, mechanism: dict) -> dict:
    tasks = []
    names = [
        "orientation",
        "newruns_discovery_inventory",
        "prediction_integrity_normalization",
        "spurious_ingest_detectability",
        "spurious_control_integration",
        "scaled_perception_ingest",
        "polarity_ablation_analysis",
        "mechanism_probe_analysis",
        "evidence_status_policy_audit",
        "failure_taxonomy_gallery",
        "residual_cue_human_audit_export",
        "second_rater_iaa_export",
        "statistical_sensitivity_plan",
        "paper_tables_figures_scaffold",
        "reviewer_attack_harness",
        "release_privacy_reproducibility_audit",
        "main500_go_nogo",
        "main500_runbook_refresh",
        "cvpr_readiness_scorecard",
        "final_validation_handoff",
        "single_master_prompt_pack_complete",
        "local_tests_and_guards",
        "no_commit",
    ]
    for i, name in enumerate(names):
        status = "complete"
        if name in {"spurious_control_integration", "main500_go_nogo", "cvpr_readiness_scorecard"} and not spurious["all_provider_gate_pass"]:
            status = "blocked_by_failed_spurious_gate"
        tasks.append({"id": f"V8_{i:02d}", "name": name, "status": status, "paper_evidence": False})
    result = {
        "schema": "certvic.v8.task_ledger.v1",
        "paper_evidence": False,
        "tasks": tasks,
        "summary": {
            "spurious_all_provider_gate_pass": spurious["all_provider_gate_pass"],
            "scaled_status": scaled["status"],
            "polarity_status": polarity["status"],
            "mechanism_status": mechanism["status"],
        },
    }
    write_json(V8 / "v8_task_ledger.json", result)
    _write_text(
        V8 / "V8_TASK_LEDGER.md",
        "# V8 Task Ledger\n\n"
        + "\n".join(f"- `{t['id']}` {t['name']}: {t['status']}" for t in tasks)
        + "\n",
    )
    return result


