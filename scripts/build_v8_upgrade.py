def _relativize_maybe(path_value: str | None) -> str:
    if not path_value:
        return ""
    p = Path(path_value)
    if p.is_absolute():
        try:
            return p.relative_to(REPO).as_posix()
        except ValueError:
            return p.name
    return path_value


